const sleep = (ms) => new Promise(r => setTimeout(r, ms));

async function run() {
  await sleep(1500);

  const versionRes = await fetch(`http://127.0.0.1:${debuggingPort}/json/list`);
  const targets = await versionRes.json();
  const pageTarget = targets.find(t => t.type === 'page') || targets[0];
  const ws = new WebSocket(pageTarget.webSocketDebuggerUrl);

  let msgId = 1;
  const pending = new Map();
  function send(method, params = {}) {
    return new Promise((resolve, reject) => {
      const id = msgId++;
      pending.set(id, { resolve, reject });
      ws.send(JSON.stringify({ id, method, params }));
    });
  }
  ws.onmessage = (event) => {
    const data = JSON.parse(event.data);
    if (data.id && pending.has(data.id)) {
      const { resolve } = pending.get(data.id);
      pending.delete(data.id);
      resolve(data.result);
    }
  };

  await new Promise(r => ws.onopen = r);
  await send('Page.enable');
  await send('Runtime.enable');

  await send('Page.navigate', { url: 'http://localhost:3000' });
  await sleep(1000);

  await send('Runtime.evaluate', {
    expression: `
      localStorage.setItem('diagramz_access_token', ${JSON.stringify(token)});
      localStorage.setItem('diagramz_theme', 'dark');
      document.cookie = 'diagramz_access_token=${token}; path=/';
    `
  });

  // Workspaces page
  await send('Page.navigate', { url: 'http://localhost:3000/dashboard/workspaces' });
  await sleep(3000);
  const shotWs = await send('Page.captureScreenshot', { format: 'png' });
  fs.writeFileSync('scripts/view-workspaces.png', Buffer.from(shotWs.data, 'base64'));

  // Settings page
  await send('Page.navigate', { url: 'http://localhost:3000/dashboard/settings' });
  await sleep(3000);
  const shotSettings = await send('Page.captureScreenshot', { format: 'png' });
  fs.writeFileSync('scripts/view-settings.png', Buffer.from(shotSettings.data, 'base64'));

  // Login page
  await send('Page.navigate', { url: 'http://localhost:3000/login' });
  await sleep(2000);
  const shotLogin = await send('Page.captureScreenshot', { format: 'png' });
  fs.writeFileSync('scripts/view-login.png', Buffer.from(shotLogin.data, 'base64'));

  await send('Browser.close');
  chrome.kill();
  console.log('Saved view-workspaces.png, view-settings.png, view-login.png');
  process.exit(0);
}

run().catch(console.error);
